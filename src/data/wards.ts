// Generate full 66 wards with stable, consistent values
export const WARDS: Ward[] = Array.from({ length: 66 }, (_, idx) => {
  const wardId = idx + 1;
  if (keyWards[wardId]) {
    return { ...keyWards[wardId] } as Ward;
  }
  
  // Deterministic scores for wards not named in the deck. They stay within 50–83 so the
  // Page 9 ranking holds (Ward 27 top at 89, Ward 12 second at 86), and Ward 60 is the
  // third ward scoring below 50 ("Underperforming Wards: 3 (Score < 50)"); the city average is 68.4.
  const pseudoScore = wardId === 60 ? 48 : 50 + ((wardId * 23) % 34);
  // Grade bands follow the Page 9 ranking table (89 A+, 86 A, 78 B+, 64 B, 52 C, 47 C Poor, 41 D)
  let grade: Ward['grade'];
  let level: Ward['level'];
  if (pseudoScore >= 87) { grade = 'A+'; level = 'Excellent'; }
  else if (pseudoScore >= 80) { grade = 'A'; level = 'Very Good'; }
  else if (pseudoScore >= 70) { grade = 'B+'; level = 'Good'; }
  else if (pseudoScore >= 55) { grade = 'B'; level = 'Average'; }
  else if (pseudoScore >= 50) { grade = 'C'; level = 'Needs Improvement'; }
  else if (pseudoScore >= 45) { grade = 'C'; level = 'Poor'; }
  else { grade = 'D'; level = 'Poor'; }

  return {
    id: wardId,
    name: `Ward ${wardId} – Division`,
    corporator: `Corporator Ward ${wardId}`,
    score: pseudoScore,
    grade,
    level,
    trend: wardId % 3 === 0 ? "↑2" : wardId % 3 === 1 ? "↓1" : "–",
    totalComplaints: 50 + (wardId % 40),
    pendingComplaints: 10 + (wardId % 15),
    inProgressComplaints: 15 + (wardId % 20),
    completedComplaints: 25 + (wardId % 25),
    overdueComplaints: 2 + (wardId % 8),
    budgetAllocatedCr: Number((3.0 + (wardId % 2.5)).toFixed(2)),
    budgetUtilizedCr: Number((2.0 + (wardId % 1.8)).toFixed(2)),
    population: 7500 + (wardId * 50),
    assignedStaffIds: [],
  };
});
